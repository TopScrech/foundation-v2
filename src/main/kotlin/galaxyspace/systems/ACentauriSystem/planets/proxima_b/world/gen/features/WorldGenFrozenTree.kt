    open fun LocationIsValidSpawn(world: World, x: Int, y: Int, z: Int): Boolean {
        val pos: BlockPos = BlockPos(x, y, z)

        val checkBlock: Block = world.getBlockState(pos.below()).getBlock()
        val blockAbove: Block = world.getBlockState(pos).getBlock()
        val blockBelow: Block = world.getBlockState(pos.below(2)).getBlock()

        for (i: Block? in GetValidSpawnBlocks()) {
            if (blockAbove !== Blocks.AIR) {
                return false
            } else if (checkBlock === i && blockAbove === this.log) {
                return false
            }
            if (checkBlock === i) {
                return true
            } else if (checkBlock === Blocks.SNOW_LAYER && blockBelow === i) {
                return true
            } else if (checkBlock.defaultBlockState().getMaterial() === Material.PLANTS && blockBelow === i) {
                return true
            }
        }
        return false
    }

